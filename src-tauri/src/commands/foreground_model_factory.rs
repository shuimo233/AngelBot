/// Inputs that affect one foreground model resolution.
#[derive(Debug, Clone, Copy)]
pub(crate) struct ForegroundModelRequest<'a> {
    pub session_id: &'a str,
    pub requested_thinking_effort: Option<&'a str>,
    pub now: i64,
}

/// Stable, non-secret model identity used by the foreground run and by the
/// internal delegation tool's durable binding.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ForegroundModelIdentity {
    pub provider: String,
    pub model: String,
    pub provider_profile_ref: String,
    pub credential_handle_ref: String,
}

/// The result required by the foreground runner.  API credentials are kept
/// inside the provider implementation and are intentionally not returned as
/// fields or serialized values.
pub(crate) struct ResolvedForegroundModel {
    pub provider: Box<dyn LlmProvider>,
    pub thinking_settings: Option<ThinkingSettings>,
    pub identity: ForegroundModelIdentity,
}

/// Deterministic offline provider used only by the compiled desktop E2E app.
/// Keeping this behind a Cargo feature prevents test behavior from being
/// enabled by an environment variable in production builds.
#[cfg(feature = "desktop-e2e")]
#[derive(serde::Deserialize)]
#[serde(tag = "type", rename_all = "snake_case", deny_unknown_fields)]
enum DesktopE2eReply {
    /// Hold one owned inference until Stop drops its streaming future.
    Pending,
    Text {
        text: String,
        #[serde(default, rename = "finishReason")]
        finish_reason: Option<String>,
        #[serde(default, rename = "expectUserContentIncludes")]
        expect_user_content_includes: Vec<String>,
        #[serde(default, rename = "forbiddenToolNames")]
        forbidden_tool_names: Vec<String>,
        #[serde(default, rename = "expectToolImageCallIds")]
        expect_tool_image_call_ids: Vec<String>,
        #[serde(default, rename = "expectCurrentDesktopObservation")]
        expect_current_desktop_observation: Option<DesktopE2eRegionRequest>,
    },
    ToolCalls {
        calls: Vec<crate::llm::ToolCall>,
        #[serde(default)]
        text: Option<String>,
    },
    /// Resolve the exact delivery identifier from the trusted structured
    /// context injected by the foreground assembler.  A static E2E fixture
    /// cannot know the durable identifier generated by the real delegation
    /// path, so it must never carry one in its script.
    DeliveryReview {
        decision: DesktopE2eDeliveryDecision,
        #[serde(default)]
        text: Option<String>,
    },
    DesktopObservedRegion(DesktopE2eRegionRequest),
    DesktopObservedControl(DesktopE2eControlRequest),
    AutomationStop {
        #[serde(rename = "callId")]
        call_id: String,
        #[serde(rename = "sourceCallId")]
        source_call_id: String,
        title: String,
    },
}

